import 'dart:io';
import 'dart:typed_data';

import 'package:bull_sdk/src/checked_u8_list.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('byte lists preserve valid values and reject truncation', () {
    final bytes = [0, 127, 255];
    expect(checkedU8List(bytes), same(bytes));
    final typed = Uint8List.fromList(bytes);
    expect(checkedU8List(typed), same(typed));
    expect(() => checkedU8List([256]), throwsRangeError);
    expect(() => checkedU8List([-1]), throwsRangeError);
  });

  test('generated byte codec validates before allocating native memory', () {
    final source = File(
      'lib/src/rust/frb_generated.io.dart',
    ).readAsStringSync();
    final start = source.indexOf(' cst_encode_list_prim_u_8_loose(');
    expect(start, greaterThanOrEqualTo(0));
    final codec = source.substring(start, source.indexOf('\n  }', start));
    final validation = codec.indexOf('checkedU8List(raw)');
    final allocation = codec.indexOf('wire.cst_new_list_prim_u_8_loose(');
    expect(validation, greaterThanOrEqualTo(0));
    expect(allocation, greaterThan(validation));
    expect(codec, contains('setAll(0, bytes)'));
  });
}
